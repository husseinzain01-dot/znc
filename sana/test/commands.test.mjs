// Sana's understanding of Iraqi Arabic, as speech recognition writes it.
import { understand, normalize, timeText, dateText, weatherText, findCity } from '../src/commands.js';
let bad = 0;
const ok = (c, m) => { console.log(c ? '  ok ' : '  BAD', m); if (!c) bad++; };
const is = (said, intent, extra = {}, ctx = {}) => {
  const r = understand(said, ctx);
  const good = r.intent === intent && Object.entries(extra).every(([k, v]) => JSON.stringify(k === 'target' ? r.target?.label : k === 'city' ? r.city?.name : r[k]) === JSON.stringify(v));
  ok(good, `«${said}» → ${r.intent}${r.dir ? ' ' + r.dir : ''}${r.target ? ' ' + r.target.label : ''}${r.city ? ' ' + r.city.name : ''}${r.reply ? ' — ' + r.reply : ''}`);
};
ok(normalize('گولي شكِد الساعة؟') === 'كولي شكد الساعه', 'normalize: Iraqi letters, diacritics, ة');
is('سنا ممكن تفتحين شكلك؟', 'figure');
is('افتحي شكلك رجاءً', 'figure', { figure: true });
is('يا سنا اظهري', 'figure');
is('بيني نفسك', 'figure');
is('ارجعي كرة', 'orb', { figure: false });
is('اختفي', 'orb');
is('التفتي يمين', 'turn', { dir: 'right' });
is('لفي على اليسار', 'turn', { dir: 'left' });
is('باوعيني', 'turn', { dir: 'front' });
is('شكد الساعة هسه', 'time');
is('شنو التاريخ اليوم', 'date');
is('شلون الجو', 'weather', { city: 'بغداد' });
is('شلون الطقس بالبصرة', 'weather', { city: 'البصره' });
is('درجة الحرارة باربيل', 'weather', { city: 'اربيل' });
is('افتحي يوتيوب', 'open', { target: 'يوتيوب' });
is('شغلي الحاسبة', 'open', { target: 'الحاسبة' });
is('افتحيلي برنامج فرعون', 'open', { target: 'فرعون' });
is('افتح لي جوجل', 'open', { target: 'كوكل' });
is('السلام عليكم', 'hello');
is('صباح الخير سنا', 'hello');
is('شلونك', 'howareyou');
is('شنو اسمك', 'who');
is('شتكدرين تسوين', 'help');
is('احجيلي نكتة', 'joke');
is('شكراً', 'thanks');
is('عاشت ايدج', 'thanks');
is('اسكتي', 'hush');
is('سدي البرنامج', 'close');
is('سنا', 'name');
is('يا سنا', 'name');
is('سنا شنو عاصمة فرنسا', 'unknown');
is('هاي شنو هذا', 'none');
is('', 'none');
ok(/الساعة 4 و25 دقيقة العصر/.test(timeText(new Date(2026, 9, 31, 16, 25))), timeText(new Date(2026, 9, 31, 16, 25)));
ok(timeText(new Date(2026, 9, 31, 9, 30)) === 'الساعة 9 ونص الصبح', timeText(new Date(2026, 9, 31, 9, 30)));
ok(timeText(new Date(2026, 9, 31, 20, 45)) === 'الساعة 9 إلا ربع بالليل', timeText(new Date(2026, 9, 31, 20, 45)));
ok(dateText(new Date(2026, 9, 31)) === 'اليوم السبت، 31 تشرين الأول 2026', dateText(new Date(2026, 9, 31)));
ok(/صافي.*41 درجة.*حر كلش/.test(weatherText('بغداد', { temperature: 41.2, code: 0 })), weatherText('بغداد', { temperature: 41.2, code: 0 }));
ok(findCity(normalize('بالسليمانية')).name === 'السليمانيه', 'city with a prefix');
if (bad) { console.log(`\n${bad} FAILED`); process.exit(1); }
console.log('\nALL PASSED');
